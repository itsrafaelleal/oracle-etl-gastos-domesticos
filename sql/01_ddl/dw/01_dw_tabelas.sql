SET SQLBLANKLINES ON;
WHENEVER SQLERROR CONTINUE;

-- 1. DIMENSÃO CALENDÁRIO (Role-Playing: Data Transação e Competência)
CREATE TABLE dim_calendario (
    sk_data             NUMBER(8)    CONSTRAINT pk_dim_calendario PRIMARY KEY,
    dt_data             DATE         NOT NULL,
    nr_ano              NUMBER(4)    NOT NULL,
    nr_mes              NUMBER(2)    NOT NULL,
    nm_mes              VARCHAR2(20) NOT NULL,
    nm_mes_abrev        VARCHAR2(3)  NOT NULL,
    nr_ano_mes          NUMBER(6)    NOT NULL,
    ds_ano_mes          VARCHAR2(7)  NOT NULL,
    nr_trimestre        NUMBER(1)    NOT NULL,
    ds_trimestre        VARCHAR2(2)  NOT NULL,
    nr_semestre         NUMBER(1)    NOT NULL,
    ds_semestre         VARCHAR2(2)  NOT NULL,
    nr_dia_mes          NUMBER(2)    NOT NULL,
    nr_dia_semana       NUMBER(1)    NOT NULL,
    nm_dia_semana       VARCHAR2(20) NOT NULL,
    fl_fim_semana       CHAR(1)      NOT NULL,
    CONSTRAINT ck_dim_cal_fds CHECK (fl_fim_semana IN ('S', 'N'))
);

COMMENT ON TABLE dim_calendario IS 'Dimensão Calendário única para role-playing no DW e Power BI.';

-- 2. DIMENSÃO RESPONSÁVEL
CREATE TABLE dim_responsavel (
    sk_responsavel      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
                        CONSTRAINT pk_dim_responsavel PRIMARY KEY,
    nm_responsavel      VARCHAR2(100) NOT NULL CONSTRAINT uk_dim_resp_nome UNIQUE,
    dt_cadastro         DATE DEFAULT SYSDATE NOT NULL
);

COMMENT ON TABLE dim_responsavel IS 'Dimensão Responsável: identifica os titulares dos gastos orçamentários.';

-- 3. DIMENSÃO CLASSIFICAÇÃO (Star Schema: Categoria, Subcategoria e Natureza Tipo)
CREATE TABLE dim_classificacao (
    sk_classificacao    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
                        CONSTRAINT pk_dim_classificacao PRIMARY KEY,
    nm_categoria        VARCHAR2(100) NOT NULL,
    nm_subcategoria     VARCHAR2(100) NOT NULL,
    tp_natureza         VARCHAR2(50)  NOT NULL,
    dt_atualizacao      DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT uk_dim_classificacao UNIQUE (nm_categoria, nm_subcategoria)
);

COMMENT ON TABLE dim_classificacao IS 'Dimensão Classificação desnormalizada (Star Schema) eliminando ambiguidade hierárquica.';

-- 4. TABELA FATO: MOVIMENTAÇÃO FINANCEIRA
CREATE TABLE fato_movimentacao (
    sk_movimentacao         NUMBER GENERATED ALWAYS AS IDENTITY
                            CONSTRAINT pk_fato_movimentacao PRIMARY KEY,
    id_lote                 NUMBER NOT NULL,
    id_origem               NUMBER(10) NOT NULL,
    sk_data_transacao       NUMBER(8) NOT NULL,
    sk_data_competencia     NUMBER(8) NOT NULL,
    sk_responsavel          NUMBER NOT NULL,
    sk_classificacao        NUMBER NOT NULL,
    ds_descricao            VARCHAR2(500) NOT NULL,
    vl_movimentacao         NUMBER(12, 2) NOT NULL,
    fl_outlier              CHAR(1) DEFAULT 'N' NOT NULL,
    fl_lag_suspeito         CHAR(1) DEFAULT 'N' NOT NULL,
    ds_observacao           VARCHAR2(500),
    hash_negocio            RAW(32) NOT NULL,
    dt_carga                TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_fato_data_trans FOREIGN KEY (sk_data_transacao)
        REFERENCES dim_calendario (sk_data),
    CONSTRAINT fk_fato_data_comp FOREIGN KEY (sk_data_competencia)
        REFERENCES dim_calendario (sk_data),
    CONSTRAINT fk_fato_resp FOREIGN KEY (sk_responsavel)
        REFERENCES dim_responsavel (sk_responsavel),
    CONSTRAINT fk_fato_class FOREIGN KEY (sk_classificacao)
        REFERENCES dim_classificacao (sk_classificacao),
    CONSTRAINT fk_fato_lote FOREIGN KEY (id_lote)
        REFERENCES ctl_lote (id_lote) ON DELETE CASCADE,
    CONSTRAINT uk_fato_origem UNIQUE (id_origem)
);

-- Índices nas Foreign Keys da Fato (Boas práticas Oracle: elimina table locks em cascata)
CREATE INDEX ix_fato_data_trans ON fato_movimentacao (sk_data_transacao);
CREATE INDEX ix_fato_data_comp  ON fato_movimentacao (sk_data_competencia);
CREATE INDEX ix_fato_resp       ON fato_movimentacao (sk_responsavel);
CREATE INDEX ix_fato_class      ON fato_movimentacao (sk_classificacao);
CREATE INDEX ix_fato_lote       ON fato_movimentacao (id_lote);

COMMENT ON TABLE fato_movimentacao IS 'Fato de Movimentações Financeiras: grão no menor nível da transação.';
